// displayName turns a slug into a human-readable title.
// What: Hyphen-split capitalization for the generated name field.
// Why: Generated metadata must already satisfy the 3-120 character rule.
func displayName(id string) string {
	parts := strings.Split(id, "-")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	name := strings.Join(parts, " ")
	if name == "" {
		name = "New Plugin"
	}
	return name
}

