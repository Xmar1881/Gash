// Package scaffold generates review-ready Tier 1 and Tier 2 plugin skeletons.
// What: Template plus passing fixture generation for `gash plugins new`.
// Why: New contributors must start from a skeleton that already passes
// `gash plugins validate` and `gash plugins test` on day one.
package scaffold

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// Tier identifies the generated skeleton kind.
// What: Supported drop-in tiers for scaffolding.
// Why: Tier 3 needs a binary and never qualifies for one-file generation.
type Tier string

const (
	// TierYAML selects the declarative Tier 1 template.
	TierYAML Tier = "yaml"
	// TierJS selects the sandboxed Tier 2 template.
	TierJS Tier = "js"
)

var slugRe = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// ValidateID checks the plugin slug before any file is written.
// What: Slug plus length gate shared by the CLI and tests.
// Why: Failing fast keeps bad names out of the registry and the docs.
func ValidateID(id string) error {
	if id == "" {
		return fmt.Errorf("scaffold: id is required: %w", errValidation())
	}
	if len(id) > 64 || !slugRe.MatchString(id) {
		return fmt.Errorf("scaffold: id %q must match ^[a-z0-9]+(-[a-z0-9]+)*$ (<=64): %w", id, errValidation())
	}
	return nil
}

// ParseTier normalizes the --tier flag value.
// What: Accepts yaml, yml, json as Tier 1 and js as Tier 2.
// Why: One parser keeps CLI errors identical everywhere the flag appears.
func ParseTier(raw string) (Tier, error) {
	switch strings.ToLower(strings.TrimSpace(raw)) {
	case "yaml", "yml", "json", "":
		return TierYAML, nil
	case "js":
		return TierJS, nil
	default:
		return "", fmt.Errorf("scaffold: tier must be yaml|js (got %q): %w", raw, errValidation())
	}
}

// Result describes what Generate wrote to disk.
// What: Plugin path plus fixture root for CLI output.
// Why: Callers print deterministic next steps from these exact paths.
type Result struct {
	// PluginPath is the generated plugin file.
	PluginPath string
	// FixtureRoot is the generated tests/fixtures/<id>/ directory.
	FixtureRoot string
	// Tier is the generated tier.
	Tier Tier
}

// Generate writes a plugin skeleton plus passing example fixtures.
// What: Creates <dir>/<id>.<ext> and <dir>/tests/fixtures/<id>/{positive,negative}.
// Why: The skeleton must satisfy the fixture requirement (positive plus
// negative) and the 0.99 precision gate without further edits.
func Generate(dir, id string, tier Tier, force bool) (*Result, error) {
	if err := ValidateID(id); err != nil {
		return nil, err
	}
	if dir == "" {
		dir = "."
	}
	ext := ".yaml"
	template := YAMLTemplate(id)
	oracle := "header"
	if tier == TierJS {
		ext = ".js"
		template = JSTemplate(id)
		oracle = "reflection"
	}
	pluginPath := filepath.Join(dir, id+ext)
	if !force {
		if _, err := os.Stat(pluginPath); err == nil {
			return nil, fmt.Errorf("scaffold: %s already exists (use --force to overwrite): %w", pluginPath, errExists())
		}
	}
	if err := os.MkdirAll(filepath.Dir(pluginPath), 0o755); err != nil {
		return nil, fmt.Errorf("scaffold: mkdir %s: %w", filepath.Dir(pluginPath), err)
	}
	if err := os.WriteFile(pluginPath, []byte(template), 0o644); err != nil {
		return nil, fmt.Errorf("scaffold: write %s: %w", pluginPath, err)
	}
	fixtureRoot := filepath.Join(dir, "tests", "fixtures", id)
	if err := writeFixtures(fixtureRoot, oracle, force); err != nil {
		return nil, err
	}
	return &Result{PluginPath: pluginPath, FixtureRoot: fixtureRoot, Tier: tier}, nil
}

// YAMLTemplate returns the Tier 1 declarative skeleton.
// What: Header-oracle plugin with safe defaults and a fixture pointer.
// Why: Header evidence is deterministic and offline-testable, so the fresh
// skeleton passes the precision gate with zero network access.
func YAMLTemplate(id string) string {
	return `# SPDX-License-Identifier: AGPL-3.0-only
# Copyright (C) 2026 Xmar1881 / GASH contributors
# Module: github.com/Xmar1881/Gash
#
# File: ` + id + `.yaml
# What: Tier 1 starter plugin generated by ` + "`gash plugins new`" + `.
# Why: Safe-by-default header check that passes validate plus test immediately.

id: ` + id + `
name: ` + displayName(id) + `
description: Starter Tier 1 plugin for ` + id + `; detects absent security headers via passive response analysis.
author: GASH contributors
severity: low
tags: [headers, misconfig]
safe: true
deep: false
active: false
requires_auth: false
phase: probe
order: 50
api_version: "1.0"
tests: tests/fixtures/` + id + `/
request:
  method: GET
oracle:
  name: header
  params:
    mode: absent
`
}

// JSTemplate returns the Tier 2 sandboxed skeleton.
// What: Reflection-oracle plugin with the fixed frontmatter plus run().
// Why: Mirrors the documented JS contract so inference, fixtures, and the
// sandbox bindings agree from the first `plugins test` run.
func JSTemplate(id string) string {
	return `/* ---
id: ` + id + `
name: ` + displayName(id) + `
description: Starter Tier 2 plugin for ` + id + `; detects reflected canary in executable HTML contexts.
author: GASH contributors
severity: high
tags: [xss, client]
safe: true
deep: false
active: false
requires_auth: false
phase: probe
order: 50
api_version: "1.0"
tests: tests/fixtures/` + id + `/
--- */
// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (C) 2026 Xmar1881 / GASH contributors
// Module: github.com/Xmar1881/Gash
//
// File: ` + id + `.js
// What: Tier 2 starter plugin generated by ` + "`gash plugins new`" + `.
// Why: Minimal executable-context reflection check behind host.oracles.

function run(probe, ctx) {
  const points = ctx.injectionPoints();
  const candidates = [];
  for (const point of points) {
    const canary = probe.canary();
    const resp = probe.send(point.withValue(canary));
    const ev = host.oracles.reflection(resp, canary, ["html", "attr", "script"]);
    if (ev) {
      candidates.push(host.candidate(point, "reflected-xss", ev));
    }
  }
  return candidates;
}
`
}

// writeFixtures creates one positive plus two negative cases per oracle.
// What: Offline JSON fixtures matching plugintest.Evaluate expectations.
// Why: Positive plus negative is mandatory; the pair below yields precision
// 1.00 so the skeleton clears the 0.99 gate untouched.
func writeFixtures(root, oracle string, force bool) error {
	posDir := filepath.Join(root, "positive")
	negDir := filepath.Join(root, "negative")
	if err := os.MkdirAll(posDir, 0o755); err != nil {
		return fmt.Errorf("scaffold: mkdir %s: %w", posDir, err)
	}
	if err := os.MkdirAll(negDir, 0o755); err != nil {
		return fmt.Errorf("scaffold: mkdir %s: %w", negDir, err)
	}
	cases := fixtureCases(oracle)
	for _, c := range cases {
		target := filepath.Join(root, c.rel)
		if !force {
			if _, err := os.Stat(target); err == nil {
				continue
			}
		}
		data, err := json.MarshalIndent(c.body, "", "  ")
		if err != nil {
			return fmt.Errorf("scaffold: encode %s: %w", c.rel, err)
		}
		if err := os.WriteFile(target, append(data, '\n'), 0o644); err != nil {
			return fmt.Errorf("scaffold: write %s: %w", target, err)
		}
	}
	return nil
}

type fixtureCase struct {
	rel  string
	body map[string]any
}

